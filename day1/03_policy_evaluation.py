#
# 오늘은 규칙을 전부 알고 있는 경우입니다. 지도를 다 갖고 있는 셈이죠.
# 그러면 ==직접 걸어 보지 않고 계산만으로== 답을 낼 수 있습니다.
#
# 계산의 핵심이 벨만 방정식입니다.
#   여기가 얼마나 좋은가 = 지금 받는 점수 + 감마 x 다음 칸이 얼마나 좋은가
# ============================================================

gamma = 1.0                 # 미래를 얼마나 챙길지. 1.0 = 지금과 똑같이 챙긴다.
theta = 1e-6                # 값이 이만큼도 안 변하면 "다 됐다"고 본다

